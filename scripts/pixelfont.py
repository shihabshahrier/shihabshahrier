GLYPH_W = 5
GLYPH_H = 7
TRACKING = 1  # blank columns between glyphs, in font pixels

_FALLBACK = GLYPHS["?"]


def text_width(text, scale=1, tracking=TRACKING):
    """Rendered width in SVG units. Trailing tracking is not counted."""
    if not text:
        return 0
    n = len(text)
    return (n * GLYPH_W + (n - 1) * tracking) * scale


def text_height(scale=1):
    return GLYPH_H * scale


def fit_scale(text, max_width, max_scale, min_scale=1, tracking=TRACKING):
    """Largest integer scale at which `text` fits inside `max_width`."""
    for scale in range(max_scale, min_scale - 1, -1):
        if text_width(text, scale, tracking) <= max_width:
            return scale
    return min_scale


def text_pixels(text, x, y, scale=1, tracking=TRACKING):
    """Yield (px, py, w, h) rects for `text`, top-left anchored at (x, y).

    Horizontal runs of lit pixels are merged into one rect to keep the SVG small.
    """
    cursor = x
    for char in text.upper():
        glyph = GLYPHS.get(char, _FALLBACK)
        for row_index, row in enumerate(glyph):
            col = 0
            while col < GLYPH_W:
                if row[col] == "1":
                    run = 1
                    while col + run < GLYPH_W and row[col + run] == "1":
                        run += 1
                    yield (
                        cursor + col * scale,
                        y + row_index * scale,
                        run * scale,
                        scale,
                    )
                    col += run
                else:
                    col += 1
        cursor += (GLYPH_W + tracking) * scale
